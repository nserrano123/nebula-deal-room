-- =====================================================================
-- Proposal versions: a new meeting updates a proposal that was already sent.
--
--  * A proposal sent outside Nebula (a PDF) can be imported as the version
--    the customer has today.
--  * Every new version keeps a link to the one before it, the meetings it
--    answers and a change log: what was asked, by whom, and what changed.
--  * Negotiated proposals keep the owner's prices. Postgres still does all
--    the arithmetic: subtotals, discounts, totals and payment schedules.
--    A line without a price stays "pending" and blocks approval.
-- =====================================================================
SET search_path = nebula, public;

-- ---------------------------------------------------------------------
-- Schema
-- ---------------------------------------------------------------------
ALTER TABLE proposal ADD COLUMN IF NOT EXISTS parent_proposal_id uuid REFERENCES proposal(id);
ALTER TABLE proposal ADD COLUMN IF NOT EXISTS source char(1) NOT NULL DEFAULT 'N';
ALTER TABLE proposal ADD COLUMN IF NOT EXISTS pricing_mode char(1) NOT NULL DEFAULT 'C';
ALTER TABLE proposal ADD COLUMN IF NOT EXISTS external_ref text;
ALTER TABLE proposal ADD COLUMN IF NOT EXISTS prepared_for jsonb NOT NULL DEFAULT '[]';
ALTER TABLE proposal ALTER COLUMN brief_id DROP NOT NULL;   -- an imported proposal has no meeting brief

DO $$ BEGIN
    ALTER TABLE proposal ADD CONSTRAINT proposal_source_chk CHECK (source IN ('N','I'));
EXCEPTION WHEN duplicate_object THEN NULL; END $$;
DO $$ BEGIN
    ALTER TABLE proposal ADD CONSTRAINT proposal_pricing_mode_chk CHECK (pricing_mode IN ('C','M'));
EXCEPTION WHEN duplicate_object THEN NULL; END $$;

-- X = superseded by a newer version that was sent
ALTER TABLE proposal DROP CONSTRAINT IF EXISTS proposal_status_check;
ALTER TABLE proposal ADD CONSTRAINT proposal_status_check CHECK (status IN ('D','P','S','V','A','R','X'));

ALTER TABLE proposal_line ALTER COLUMN unit_price DROP NOT NULL;
ALTER TABLE proposal_line ALTER COLUMN subtotal  DROP NOT NULL;

-- Which meetings a version answers (one or more)
CREATE TABLE IF NOT EXISTS proposal_brief (
    proposal_id uuid NOT NULL REFERENCES proposal(id) ON DELETE CASCADE,
    brief_id    uuid NOT NULL REFERENCES meeting_brief(id),
    PRIMARY KEY (proposal_id, brief_id)
);

-- What changed from the previous version and why
CREATE TABLE IF NOT EXISTS proposal_change (
    id            bigserial PRIMARY KEY,
    proposal_id   uuid NOT NULL REFERENCES proposal(id) ON DELETE CASCADE,
    change_no     int NOT NULL,
    origin        char(1) NOT NULL CHECK (origin IN ('P','R')),          -- P computed by Postgres, R answers a request
    kind          char(1) NOT NULL CHECK (kind IN ('A','M','R','C')),    -- added, modified, removed, clarified
    topic         text NOT NULL,
    before_text   text,
    after_text    text,
    request_quote text,                                                  -- the customer's words, verbatim
    requested_by  text,
    brief_id      uuid REFERENCES meeting_brief(id),
    UNIQUE (proposal_id, change_no)
);

-- Priced extras the owner sells besides the plan (hourly rates, packs, add-ons).
-- The updater agent may only quote prices that live here or in the previous version.
CREATE TABLE IF NOT EXISTS price_item (
    id            uuid PRIMARY KEY DEFAULT gen_random_uuid(),
    tenant_id     uuid NOT NULL REFERENCES tenant(id),
    code          text NOT NULL,
    name          text NOT NULL,
    unit_label    text NOT NULL,
    price         numeric(14,4) NOT NULL,
    currency      char(3) NOT NULL,
    recurrence    char(1) NOT NULL CHECK (recurrence IN ('M','O','U')),   -- monthly, one-time, per use
    confirmed     boolean NOT NULL DEFAULT true,                          -- false: proposed, the owner has not confirmed it
    audit_status  char(1) NOT NULL DEFAULT 'A' CHECK (audit_status IN ('A','D')),
    deleted_at    timestamptz,
    UNIQUE (tenant_id, code)
);

INSERT INTO code_label (domain, code, label) VALUES
 ('proposal_status','X','Superseded by a newer version'),
 ('proposal_source','N','Generated by Nebula'), ('proposal_source','I','Imported'),
 ('pricing_mode','C','Price list'), ('pricing_mode','M','Negotiated'),
 ('change_origin','P','Price (computed)'), ('change_origin','R','Customer request'),
 ('change_kind','A','Added'), ('change_kind','M','Changed'), ('change_kind','R','Removed'), ('change_kind','C','Clarified'),
 ('recurrence','U','Per use'),
 ('line_kind','L','Item'), ('line_kind','D','Discount')
ON CONFLICT (domain, code) DO UPDATE SET label = EXCLUDED.label;

-- ---------------------------------------------------------------------
-- Negotiated quote: the owner gives lines and terms; Postgres does the math.
--
-- line: {concept_code, concept_name, description?, quantity, unit_price|null,
--        currency, recurrence_code 'M'|'O', note?}
-- discount line: {kind:'D', concept_code, concept_name, discount_pct,
--                 currency, recurrence_code}  -> applies to the item lines
--                 with the same currency and recurrence
-- terms: {payment_schedule:[{label, pct}], validity, execution, timeline,
--         support:[…], notes:[…], rates:[{code,name,unit_label,price,currency}],
--         edoc_tiers:[{up_to, price, currency}], …}  (free-form text kept as is)
-- ---------------------------------------------------------------------
CREATE OR REPLACE FUNCTION fn_manual_quote(p_lines jsonb, p_terms jsonb DEFAULT '{}')
RETURNS jsonb LANGUAGE plpgsql STABLE SET search_path = nebula, public AS $$
DECLARE
    l jsonb; v_out jsonb := '[]'; v_no int := 0; v_kind char(1); v_rec char(1); v_cur text;
    v_qty numeric; v_price numeric; v_sub numeric; v_pct numeric; v_base numeric;
    v_pending int := 0; v_totals jsonb; v_terms jsonb := coalesce(p_terms, '{}'); v_sched jsonb := '[]';
    s jsonb; v_pct_sum numeric := 0; v_one_time numeric; v_one_cur text; v_users numeric;
BEGIN
    IF jsonb_typeof(p_lines) <> 'array' OR jsonb_array_length(p_lines) = 0 THEN
        RAISE EXCEPTION 'A proposal needs at least one priced line.';
    END IF;

    -- 1. Item lines
    FOR l IN SELECT * FROM jsonb_array_elements(p_lines) LOOP
        v_kind := coalesce(l->>'kind', 'L');
        CONTINUE WHEN v_kind = 'D';
        v_no  := v_no + 1;
        v_rec := coalesce(l->>'recurrence_code', 'M');
        v_cur := upper(coalesce(l->>'currency', ''));
        IF coalesce(trim(l->>'concept_name'), '') = '' THEN
            RAISE EXCEPTION 'Line % has no name.', v_no;
        END IF;
        IF v_rec NOT IN ('M','O') THEN
            RAISE EXCEPTION 'Line % (%): recurrence % is not valid. Use M (Monthly) or O (One-time).', v_no, l->>'concept_name', v_rec;
        END IF;
        IF v_cur !~ '^[A-Z]{3}$' THEN
            RAISE EXCEPTION 'Line % (%) needs a 3-letter currency such as USD or COP.', v_no, l->>'concept_name';
        END IF;
        v_qty := coalesce(nullif(l->>'quantity', '')::numeric, 1);
        IF v_qty < 0 THEN
            RAISE EXCEPTION 'Line % (%): the quantity cannot be negative.', v_no, l->>'concept_name';
        END IF;
        v_price := nullif(l->>'unit_price', '')::numeric;
        IF v_price IS NOT NULL AND v_price < 0 THEN
            RAISE EXCEPTION 'Line % (%): use a discount line instead of a negative price.', v_no, l->>'concept_name';
        END IF;
        v_sub := CASE WHEN v_price IS NULL THEN NULL ELSE round(v_qty * v_price, 2) END;
        IF v_price IS NULL THEN v_pending := v_pending + 1; END IF;

        v_out := v_out || jsonb_build_object(
            'line_no', v_no, 'kind_code', 'L', 'kind_label', fn_label('line_kind', 'L'),
            'concept_code', coalesce(nullif(l->>'concept_code', ''), 'LINE-' || v_no),
            'concept_name', l->>'concept_name', 'description', l->>'description',
            'quantity', v_qty, 'unit_price', v_price, 'subtotal', v_sub,
            'currency', v_cur, 'recurrence_code', v_rec, 'recurrence_label', fn_label('recurrence', v_rec),
            'price_pending', v_price IS NULL, 'note', l->>'note');
    END LOOP;

    -- 2. Discount lines, computed over the item lines they apply to
    FOR l IN SELECT * FROM jsonb_array_elements(p_lines) WHERE value->>'kind' = 'D' LOOP
        v_no  := v_no + 1;
        v_rec := coalesce(l->>'recurrence_code', 'O');
        v_cur := upper(coalesce(l->>'currency', ''));
        v_pct := nullif(l->>'discount_pct', '')::numeric;
        IF v_pct IS NULL OR v_pct <= 0 OR v_pct >= 100 THEN
            RAISE EXCEPTION 'Discount % needs a percentage between 0 and 100.', coalesce(l->>'concept_name', v_no::text);
        END IF;
        SELECT sum((x->>'subtotal')::numeric) INTO v_base
          FROM jsonb_array_elements(v_out) x
         WHERE x->>'kind_code' = 'L' AND x->>'currency' = v_cur AND x->>'recurrence_code' = v_rec;
        IF v_base IS NULL THEN
            RAISE EXCEPTION 'Discount % applies to % % lines, and there are none.', l->>'concept_name', v_cur, fn_label('recurrence', v_rec);
        END IF;
        v_out := v_out || jsonb_build_object(
            'line_no', v_no, 'kind_code', 'D', 'kind_label', fn_label('line_kind', 'D'),
            'concept_code', coalesce(nullif(l->>'concept_code', ''), 'DISC-' || v_no),
            'concept_name', l->>'concept_name', 'description', l->>'description',
            'quantity', 1, 'unit_price', -round(v_base * v_pct / 100, 2), 'subtotal', -round(v_base * v_pct / 100, 2),
            'discount_pct', v_pct, 'discount_base', v_base,
            'currency', v_cur, 'recurrence_code', v_rec, 'recurrence_label', fn_label('recurrence', v_rec),
            'price_pending', false, 'note', l->>'note');
    END LOOP;

    -- 3. Totals per currency and recurrence (pending lines count as zero and are flagged)
    SELECT coalesce(jsonb_agg(jsonb_build_object('total', t.total, 'currency', t.currency,
                    'recurrence_code', t.rec, 'recurrence_label', fn_label('recurrence', t.rec))
                    ORDER BY t.rec, t.currency), '[]')
      INTO v_totals
      FROM (SELECT x->>'currency' AS currency, x->>'recurrence_code' AS rec,
                   sum(coalesce((x->>'subtotal')::numeric, 0)) AS total
              FROM jsonb_array_elements(v_out) x GROUP BY 1, 2) t;

    -- 4. Payment schedule for the one-time total
    SELECT (x->>'total')::numeric, x->>'currency' INTO v_one_time, v_one_cur
      FROM jsonb_array_elements(v_totals) x WHERE x->>'recurrence_code' = 'O' LIMIT 1;
    IF jsonb_typeof(v_terms->'payment_schedule') = 'array' AND jsonb_array_length(v_terms->'payment_schedule') > 0 THEN
        FOR s IN SELECT * FROM jsonb_array_elements(v_terms->'payment_schedule') LOOP
            v_pct_sum := v_pct_sum + (s->>'pct')::numeric;
            v_sched := v_sched || jsonb_build_object('label', s->>'label', 'pct', (s->>'pct')::numeric,
                        'amount', round(coalesce(v_one_time, 0) * (s->>'pct')::numeric / 100, 2), 'currency', v_one_cur);
        END LOOP;
        IF v_pct_sum <> 100 THEN
            RAISE EXCEPTION 'The payment schedule adds up to % percent; it must add up to 100 percent.', v_pct_sum;
        END IF;
        v_terms := jsonb_set(v_terms, '{payment_schedule}', v_sched);
    END IF;

    SELECT max((x->>'quantity')::numeric) INTO v_users FROM jsonb_array_elements(v_out) x
     WHERE x->>'concept_code' LIKE 'LIC-%' OR x->>'concept_code' = 'USERS';

    RETURN jsonb_build_object(
        'pricing_mode_code', 'M', 'pricing_mode_label', fn_label('pricing_mode', 'M'),
        'lines', v_out, 'totals', v_totals, 'terms', v_terms,
        'pending_prices', v_pending,
        'inputs', CASE WHEN v_users IS NULL THEN NULL ELSE jsonb_build_object('users', v_users) END,
        'flags', CASE WHEN v_pending > 0
                      THEN jsonb_build_array(format('%s line(s) without a price: set them before approving.', v_pending))
                      ELSE '[]'::jsonb END);
END $$;

-- Saves the lines of a quote into proposal_line (for reporting)
CREATE OR REPLACE FUNCTION fn_store_lines(p_proposal_id uuid, p_quote jsonb)
RETURNS void LANGUAGE plpgsql SET search_path = nebula, public AS $$
DECLARE l jsonb;
BEGIN
    DELETE FROM proposal_line WHERE proposal_id = p_proposal_id;
    FOR l IN SELECT * FROM jsonb_array_elements(p_quote->'lines') LOOP
        INSERT INTO proposal_line (proposal_id, line_no, concept_code, concept_name, quantity,
                                   unit_price, currency, subtotal, recurrence, note)
        VALUES (p_proposal_id, (l->>'line_no')::int, l->>'concept_code', l->>'concept_name',
                (l->>'quantity')::numeric, nullif(l->>'unit_price', '')::numeric, l->>'currency',
                nullif(l->>'subtotal', '')::numeric, l->>'recurrence_code', l->>'note');
    END LOOP;
END $$;

-- ---------------------------------------------------------------------
-- Import a proposal that was already sent outside Nebula.
-- It is stored as Sent on its original date, so the next version has a base.
-- ---------------------------------------------------------------------
CREATE OR REPLACE FUNCTION fn_import_proposal(
    p_tenant_code text, p_company text, p_external_ref text, p_issued_on date,
    p_lines jsonb, p_terms jsonb, p_narrative text,
    p_prepared_for jsonb DEFAULT '[]', p_opportunity_code text DEFAULT NULL)
RETURNS jsonb LANGUAGE plpgsql SET search_path = nebula, public AS $$
DECLARE
    t tenant; o opportunity; v_quote jsonb; v_code text; v_id uuid; v_version int; v_dup text; v_at timestamptz;
BEGIN
    t := fn_get_tenant(p_tenant_code);
    IF p_opportunity_code IS NOT NULL THEN
        o := fn_get_opportunity(t.id, p_opportunity_code);
    ELSE
        -- two statements: a STABLE lookup in the same expression would not see the new row
        v_dup := fn_create_opportunity(p_tenant_code, p_company)->>'opportunity_code';
        o := fn_get_opportunity(t.id, v_dup);
        v_dup := NULL;
    END IF;
    IF p_issued_on IS NULL OR p_issued_on > current_date THEN
        RAISE EXCEPTION 'The imported proposal needs the date it was issued (not in the future).';
    END IF;
    v_at := (p_issued_on + time '12:00') AT TIME ZONE 'America/Bogota';   -- the issue day, not midnight UTC
    IF coalesce(trim(p_external_ref), '') <> '' THEN
        SELECT code INTO v_dup FROM proposal
         WHERE tenant_id = t.id AND external_ref = p_external_ref AND audit_status = 'A';
        IF FOUND THEN
            RAISE EXCEPTION 'Proposal % (%) was already imported as %.', p_external_ref, o.company_name, v_dup;
        END IF;
    END IF;

    v_quote := fn_manual_quote(p_lines, p_terms);
    IF (v_quote->>'pending_prices')::int > 0 THEN
        RAISE EXCEPTION 'An imported proposal must have every price; % line(s) have none.', v_quote->>'pending_prices';
    END IF;

    SELECT count(*) + 1 INTO v_version FROM proposal WHERE opportunity_id = o.id;
    v_code := 'PRP-' || lpad(nextval('proposal_seq')::text, 4, '0');
    INSERT INTO proposal (tenant_id, code, opportunity_id, brief_id, version, status, quote, narrative,
                          approved_by, approved_at, sent_at, source, pricing_mode, external_ref, prepared_for, created_at)
    VALUES (t.id, v_code, o.id, NULL, v_version, 'S', v_quote, p_narrative,
            t.owner_name, v_at, v_at, 'I', 'M', nullif(trim(p_external_ref), ''),
            coalesce(p_prepared_for, '[]'), v_at)
    RETURNING id INTO v_id;
    PERFORM fn_store_lines(v_id, v_quote);

    RETURN jsonb_build_object('proposal_code', v_code, 'version', v_version,
        'opportunity_code', o.code, 'company_name', o.company_name,
        'status_code', 'S', 'status_label', fn_label('proposal_status', 'S'),
        'source_code', 'I', 'source_label', fn_label('proposal_source', 'I'),
        'quote', v_quote);
END $$;

-- Price differences of a version against the one before it, line by line (origin P).
CREATE OR REPLACE FUNCTION fn_record_price_changes(p_proposal_id uuid)
RETURNS void LANGUAGE plpgsql SET search_path = nebula, public AS $$
DECLARE p proposal; par proposal; v_no int;
BEGIN
    SELECT * INTO p FROM proposal WHERE id = p_proposal_id;
    DELETE FROM proposal_change WHERE proposal_id = p.id AND origin = 'P';
    IF p.parent_proposal_id IS NULL THEN RETURN; END IF;
    SELECT * INTO par FROM proposal WHERE id = p.parent_proposal_id;
    SELECT coalesce(max(change_no), 0) INTO v_no FROM proposal_change WHERE proposal_id = p.id;

    INSERT INTO proposal_change (proposal_id, change_no, origin, kind, topic, before_text, after_text)
    SELECT p.id, v_no + row_number() OVER (ORDER BY coalesce(n.ln, 1000 + a.ln)), 'P',
           CASE WHEN a.cc IS NULL THEN 'A' WHEN n.cc IS NULL THEN 'R' ELSE 'M' END,
           coalesce(n.cn, a.cn),
           CASE WHEN a.cc IS NULL THEN NULL ELSE format('%s × %s %s = %s %s', a.q, a.cur, a.up, a.cur, a.st) END,
           CASE WHEN n.cc IS NULL THEN NULL
                WHEN n.pend THEN format('%s × price pending', n.q)
                ELSE format('%s × %s %s = %s %s', n.q, n.cur, n.up, n.cur, n.st) END
      FROM (SELECT (x->>'line_no')::int ln, x->>'concept_code' cc, x->>'concept_name' cn, x->>'currency' cur,
                   (x->>'quantity')::numeric q, nullif(x->>'unit_price','')::numeric up, nullif(x->>'subtotal','')::numeric st
              FROM jsonb_array_elements(par.quote->'lines') x) a
      FULL JOIN
           (SELECT (x->>'line_no')::int ln, x->>'concept_code' cc, x->>'concept_name' cn, x->>'currency' cur,
                   (x->>'quantity')::numeric q, nullif(x->>'unit_price','')::numeric up, nullif(x->>'subtotal','')::numeric st,
                   coalesce((x->>'price_pending')::boolean, false) pend
              FROM jsonb_array_elements(p.quote->'lines') x) n
        ON n.cc = a.cc
     WHERE a.cc IS NULL OR n.cc IS NULL OR a.q IS DISTINCT FROM n.q OR a.st IS DISTINCT FROM n.st OR n.pend;
END $$;

-- ---------------------------------------------------------------------
-- Create the next version of a proposal from one or more new meetings.
-- p_changes: [{kind:'A'|'M'|'R'|'C', topic, before_text, after_text,
--              request_quote, requested_by, brief_code}]  (customer requests)
-- Price differences against the previous version are computed here.
-- ---------------------------------------------------------------------
CREATE OR REPLACE FUNCTION fn_create_version(
    p_tenant_code text, p_parent_code text, p_brief_codes text[],
    p_lines jsonb, p_terms jsonb, p_changes jsonb, p_narrative text,
    p_prepared_for jsonb DEFAULT NULL)
RETURNS jsonb LANGUAGE plpgsql SET search_path = nebula, public AS $$
DECLARE
    t tenant; par proposal; o opportunity; b meeting_brief; v_brief_ids uuid[] := '{}'; v_last uuid;
    v_quote jsonb; v_code text; v_id uuid; v_version int; v_no int := 0; c jsonb; v_kind char(1);
    v_open text; v_bc text;
BEGIN
    t   := fn_get_tenant(p_tenant_code);
    par := fn_get_proposal(t.id, p_parent_code);
    SELECT * INTO o FROM opportunity WHERE id = par.opportunity_id;

    IF par.status = 'D' THEN
        RAISE EXCEPTION 'Proposal % is still a Draft; edit it instead of creating a new version.', par.code;
    END IF;
    SELECT code INTO v_open FROM proposal
     WHERE parent_proposal_id = par.id AND status IN ('D','P') AND audit_status = 'A' LIMIT 1;
    IF FOUND THEN
        RAISE EXCEPTION 'Proposal % already has a version in progress (%). Finish or delete it first.', par.code, v_open;
    END IF;
    IF coalesce(array_length(p_brief_codes, 1), 0) = 0 THEN
        RAISE EXCEPTION 'A new version of % needs at least one new meeting.', par.code;
    END IF;
    FOREACH v_bc IN ARRAY p_brief_codes LOOP
        b := fn_get_brief(t.id, v_bc);
        IF b.opportunity_id <> o.id THEN
            RAISE EXCEPTION 'Meeting brief % belongs to another deal, not to % (%).', b.code, o.code, o.company_name;
        END IF;
        v_brief_ids := v_brief_ids || b.id;
    END LOOP;
    SELECT id INTO v_last FROM meeting_brief WHERE id = ANY (v_brief_ids) ORDER BY meeting_at DESC, created_at DESC LIMIT 1;

    v_quote := fn_manual_quote(p_lines, p_terms);
    SELECT max(version) + 1 INTO v_version FROM proposal WHERE opportunity_id = o.id AND audit_status = 'A';
    v_code := 'PRP-' || lpad(nextval('proposal_seq')::text, 4, '0');

    INSERT INTO proposal (tenant_id, code, opportunity_id, brief_id, version, quote, narrative,
                          parent_proposal_id, source, pricing_mode, prepared_for)
    VALUES (t.id, v_code, o.id, v_last, v_version, v_quote, p_narrative,
            par.id, 'N', 'M', coalesce(p_prepared_for, par.prepared_for))
    RETURNING id INTO v_id;
    PERFORM fn_store_lines(v_id, v_quote);
    INSERT INTO proposal_brief (proposal_id, brief_id) SELECT v_id, unnest(v_brief_ids);

    -- Customer requests and how this version answers them
    FOR c IN SELECT * FROM jsonb_array_elements(coalesce(p_changes, '[]')) LOOP
        v_kind := coalesce(c->>'kind', 'C');
        IF v_kind NOT IN ('A','M','R','C') THEN
            RAISE EXCEPTION 'Change "%" has kind %; use A (Added), M (Changed), R (Removed) or C (Clarified).', c->>'topic', v_kind;
        END IF;
        b := NULL;
        IF coalesce(c->>'brief_code', '') <> '' THEN
            b := fn_get_brief(t.id, c->>'brief_code');
        END IF;
        v_no := v_no + 1;
        INSERT INTO proposal_change (proposal_id, change_no, origin, kind, topic, before_text, after_text,
                                     request_quote, requested_by, brief_id)
        VALUES (v_id, v_no, 'R', v_kind, c->>'topic', c->>'before_text', c->>'after_text',
                c->>'request_quote', c->>'requested_by', b.id);
    END LOOP;

    PERFORM fn_record_price_changes(v_id);

    RETURN jsonb_build_object('proposal_code', v_code, 'version', v_version,
        'parent_proposal_code', par.code, 'parent_version', par.version,
        'opportunity_code', o.code, 'company_name', o.company_name,
        'status_code', 'D', 'status_label', fn_label('proposal_status', 'D'),
        'quote', v_quote, 'changes', fn_proposal_changes(v_id));
END $$;

CREATE OR REPLACE FUNCTION fn_proposal_changes(p_proposal_id uuid)
RETURNS jsonb LANGUAGE sql STABLE SET search_path = nebula, public AS $$
    SELECT coalesce(jsonb_agg(jsonb_build_object(
               'change_no', c.change_no,
               'origin_code', c.origin, 'origin_label', fn_label('change_origin', c.origin),
               'kind_code', c.kind, 'kind_label', fn_label('change_kind', c.kind),
               'topic', c.topic, 'before_text', c.before_text, 'after_text', c.after_text,
               'request_quote', c.request_quote, 'requested_by', c.requested_by,
               'brief_code', b.code, 'meeting_at', b.meeting_at)
             ORDER BY c.change_no), '[]')
      FROM proposal_change c LEFT JOIN meeting_brief b ON b.id = c.brief_id
     WHERE c.proposal_id = p_proposal_id
$$;

-- Owner edits a draft version: new lines / terms (e.g. fills a pending price).
-- Price changes are recomputed against the previous version.
CREATE OR REPLACE FUNCTION fn_set_version_pricing(p_tenant_code text, p_proposal_code text, p_lines jsonb, p_terms jsonb)
RETURNS jsonb LANGUAGE plpgsql SET search_path = nebula, public AS $$
DECLARE t tenant; p proposal; v_quote jsonb;
BEGIN
    t := fn_get_tenant(p_tenant_code);
    p := fn_get_proposal(t.id, p_proposal_code);
    IF p.status <> 'D' THEN
        RAISE EXCEPTION 'Proposal % is % (%); only a Draft can be repriced.', p.code, p.status, fn_label('proposal_status', p.status);
    END IF;
    IF p.pricing_mode <> 'M' THEN
        RAISE EXCEPTION 'Proposal % is priced from the price list; change the brief counts instead.', p.code;
    END IF;
    v_quote := fn_manual_quote(p_lines, coalesce(p_terms, p.quote->'terms'));
    UPDATE proposal SET quote = v_quote WHERE id = p.id;
    PERFORM fn_store_lines(p.id, v_quote);

    PERFORM fn_record_price_changes(p.id);
    RETURN jsonb_build_object('proposal_code', p.code, 'quote', v_quote, 'changes', fn_proposal_changes(p.id));
END $$;

-- ---------------------------------------------------------------------
-- Approval and sending, version-aware
-- ---------------------------------------------------------------------
CREATE OR REPLACE FUNCTION fn_approve_proposal(p_tenant_code text, p_proposal_code text, p_approved_by text)
RETURNS jsonb LANGUAGE plpgsql SET search_path = nebula, public AS $$
DECLARE t tenant; p proposal;
BEGIN
    t := fn_get_tenant(p_tenant_code);
    p := fn_get_proposal(t.id, p_proposal_code);
    IF p.status <> 'D' THEN
        RAISE EXCEPTION 'Proposal % is % (%); only a Draft can be approved.',
            p.code, p.status, fn_label('proposal_status', p.status);
    END IF;
    IF coalesce(trim(p.narrative), '') = '' THEN
        RAISE EXCEPTION 'Proposal % has no written text yet; generate it before approving.', p.code;
    END IF;
    IF coalesce((p.quote->>'pending_prices')::int, 0) > 0 THEN
        RAISE EXCEPTION 'Proposal % has % line(s) without a price; set them before approving.', p.code, p.quote->>'pending_prices';
    END IF;
    UPDATE proposal SET status = 'P', approved_by = p_approved_by, approved_at = now() WHERE id = p.id;
    RETURN jsonb_build_object('proposal_code', p.code, 'status_code', 'P',
                              'status_label', fn_label('proposal_status','P'), 'public_token', p.public_token);
END $$;

CREATE OR REPLACE FUNCTION fn_mark_sent(p_tenant_code text, p_proposal_code text)
RETURNS jsonb LANGUAGE plpgsql SET search_path = nebula, public AS $$
DECLARE t tenant; p proposal; v_parent text;
BEGIN
    t := fn_get_tenant(p_tenant_code);
    p := fn_get_proposal(t.id, p_proposal_code);
    IF p.status <> 'P' THEN
        RAISE EXCEPTION 'Proposal % is % (%); only an Approved proposal can be sent.',
            p.code, p.status, fn_label('proposal_status', p.status);
    END IF;
    UPDATE proposal SET status = 'S', sent_at = now() WHERE id = p.id;
    -- The version it replaces stops being the live one
    UPDATE proposal SET status = 'X' WHERE id = p.parent_proposal_id AND status IN ('S','V','P')
    RETURNING code INTO v_parent;
    RETURN jsonb_build_object('proposal_code', p.code, 'status_code', 'S',
                              'status_label', fn_label('proposal_status','S'),
                              'superseded_proposal_code', v_parent);
END $$;

-- ---------------------------------------------------------------------
-- Customer side: the room shows the version and what changed.
-- A superseded link tells the visitor which version replaced it.
-- ---------------------------------------------------------------------
CREATE OR REPLACE FUNCTION fn_public_proposal(p_token text)
RETURNS jsonb LANGUAGE plpgsql STABLE SECURITY DEFINER SET search_path = nebula, public AS $$
DECLARE p proposal; o opportunity; t tenant; par proposal; nxt proposal;
BEGIN
    p := fn_get_proposal_by_token(p_token);
    SELECT * INTO t FROM tenant WHERE id = p.tenant_id;
    IF p.status = 'X' THEN
        SELECT * INTO nxt FROM proposal WHERE parent_proposal_id = p.id AND status IN ('S','V','A','R','X')
         ORDER BY version DESC LIMIT 1;
        RAISE EXCEPTION 'Proposal % (version %) was replaced by version %. Use the most recent link from %.',
            p.code, p.version, coalesce(nxt.version::text, 'a newer one'), t.owner_name;
    END IF;
    IF p.status NOT IN ('S','V','A','R') THEN
        RAISE EXCEPTION 'Proposal % has not been sent yet.', p.code;
    END IF;
    SELECT * INTO o FROM opportunity WHERE id = p.opportunity_id;
    SELECT * INTO par FROM proposal WHERE id = p.parent_proposal_id;
    RETURN jsonb_build_object(
        'proposal_code', p.code, 'version', p.version,
        'status_code', p.status, 'status_label', fn_label('proposal_status', p.status),
        'tenant_name', t.name, 'owner_name', t.owner_name,
        'company_name', o.company_name, 'prepared_for', p.prepared_for,
        'previous_version', CASE WHEN par.id IS NULL THEN NULL
                                 ELSE jsonb_build_object('proposal_code', par.code, 'version', par.version,
                                                         'external_ref', par.external_ref, 'sent_at', par.sent_at) END,
        'changes', (SELECT coalesce(jsonb_agg(c) FILTER (WHERE c->>'origin_code' = 'R'), '[]')
                      FROM jsonb_array_elements(fn_proposal_changes(p.id)) c),
        'narrative', p.narrative, 'quote', p.quote, 'sent_at', p.sent_at);
END $$;

-- Negotiated proposals are not repriced from the price list in the room
CREATE OR REPLACE FUNCTION fn_simulate(p_token text, p_stakeholder_code text DEFAULT NULL,
                            p_users int DEFAULT NULL, p_module_codes text[] DEFAULT NULL,
                            p_employees int DEFAULT NULL, p_legal_entities int DEFAULT NULL)
RETURNS jsonb LANGUAGE plpgsql SECURITY DEFINER SET search_path = nebula, public AS $$
DECLARE
    p proposal; b meeting_brief; t tenant; pl price_plan; s stakeholder;
    v_sim jsonb; v_orig numeric; v_new numeric; v_cur text;
BEGIN
    p := fn_get_proposal_by_token(p_token);
    IF p.status NOT IN ('S','V') THEN
        RAISE EXCEPTION 'Proposal % is % (%); simulations are not available.',
            p.code, p.status, fn_label('proposal_status', p.status);
    END IF;
    SELECT * INTO t FROM tenant WHERE id = p.tenant_id;
    IF p.pricing_mode = 'M' THEN
        RAISE EXCEPTION 'Proposal % has negotiated prices; % prepares any other scenario personally.', p.code, t.owner_name;
    END IF;
    IF p_stakeholder_code IS NOT NULL THEN
        s := fn_get_stakeholder(p.opportunity_id, p_stakeholder_code);
    END IF;
    SELECT * INTO b  FROM meeting_brief WHERE id = p.brief_id;
    SELECT * INTO pl FROM price_plan WHERE id = b.plan_id;

    v_sim := fn_quote(t.code, pl.code,
                      coalesce(p_users, b.users_count),
                      coalesce(p_module_codes, b.module_codes),
                      coalesce(p_legal_entities, b.legal_entities_count),
                      coalesce(p_employees, b.employees_count),
                      b.complexity, b.vehicles_count);

    v_cur := pl.currency;
    SELECT sum((x->>'total')::numeric) INTO v_orig FROM jsonb_array_elements(p.quote->'totals') x
     WHERE x->>'recurrence_code' = 'M' AND x->>'currency' = v_cur;
    SELECT sum((x->>'total')::numeric) INTO v_new FROM jsonb_array_elements(v_sim->'totals') x
     WHERE x->>'recurrence_code' = 'M' AND x->>'currency' = v_cur;

    INSERT INTO proposal_event (proposal_id, stakeholder_id, event_type, payload)
    VALUES (p.id, s.id, 'SI', jsonb_build_object('inputs', v_sim->'inputs', 'modules', v_sim->'modules',
                                                  'monthly_total', v_new, 'currency', v_cur));

    RETURN jsonb_build_object(
        'proposal_code', p.code,
        'simulation', v_sim,
        'monthly_original', v_orig, 'monthly_simulated', v_new,
        'monthly_delta', v_new - v_orig, 'currency', v_cur,
        'message', format('This is a simulation. The official proposal changes only when %s approves it.', t.owner_name));
END $$;

