CREATE OR REPLACE FUNCTION fn_price_items(p_tenant_code text)
RETURNS jsonb LANGUAGE sql STABLE SET search_path = nebula, public AS $$
    SELECT coalesce(jsonb_agg(jsonb_build_object(
               'code', i.code, 'name', i.name, 'unit_label', i.unit_label, 'price', i.price,
               'currency', i.currency, 'recurrence_code', i.recurrence,
               'recurrence_label', fn_label('recurrence', i.recurrence),
               'confirmed', i.confirmed, 'confirmed_label', CASE WHEN i.confirmed THEN 'Confirmed' ELSE 'Proposed, not confirmed' END)
             ORDER BY i.code), '[]')
      FROM price_item i JOIN tenant t ON t.id = i.tenant_id
     WHERE t.code = p_tenant_code AND i.audit_status = 'A'
$$;

-- Every proposal with its place in the version chain
CREATE OR REPLACE VIEW v_proposal_versions AS
SELECT t.code AS tenant_code, o.code AS opportunity_code, o.company_name,
       p.code AS proposal_code, p.version, p.external_ref,
       p.status AS status_code, fn_label('proposal_status', p.status) AS status_label,
       p.source AS source_code, fn_label('proposal_source', p.source) AS source_label,
       p.pricing_mode AS pricing_mode_code, fn_label('pricing_mode', p.pricing_mode) AS pricing_mode_label,
       par.code AS parent_proposal_code, par.version AS parent_version,
       p.created_at, p.sent_at,
       coalesce((p.quote->>'pending_prices')::int, 0) AS pending_prices,
       (SELECT count(*) FROM proposal_change c WHERE c.proposal_id = p.id) AS changes
  FROM proposal p
  JOIN tenant t      ON t.id = p.tenant_id
  JOIN opportunity o ON o.id = p.opportunity_id
  LEFT JOIN proposal par ON par.id = p.parent_proposal_id
 WHERE p.audit_status = 'A';

